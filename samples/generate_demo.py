def _signed_bank(rows, acc):
    total = Decimal("0")
    seen = set()
    for r in rows:
        if r[0] != acc or r[8] in seen:  # 防重：同流水号只计一次
            continue
        seen.add(r[8])
        amt = Decimal(r[3])
        total += amt if r[4] == "收" else -amt
    return total


def _signed_vouchers(rows, acc):
    total = Decimal("0")
    for r in rows:
        if r[5] != acc or r[12] == "作废":
            continue
        amt = Decimal(r[6])
        signed = amt if r[7] == "借" else -amt
        if r[12] == "红冲":
            signed = -signed
        total += signed
    return total


def write_csv(name, header, rows):
    with (HERE / name).open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)
    print(f"  生成 {name}（{len(rows)} 行）")


